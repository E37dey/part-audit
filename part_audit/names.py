# --------------------------------------------------------------------------- phonetic key

_HEB_KEY = {"א": "", "ב": "B", "ג": "G", "ד": "D", "ה": "", "ו": "", "ז": "Z", "ח": "K", "ט": "T", "י": "",
            "כ": "K", "ל": "L", "מ": "M", "נ": "N", "ס": "S", "ע": "", "פ": "P", "צ": "C", "ק": "K", "ר": "R",
            "ש": "S", "ת": "T"}
_LAT_DIGRAPHS = [("sh", "S"), ("ch", "K"), ("kh", "K"), ("tz", "C"), ("ts", "C"), ("ph", "P"), ("th", "T")]
_LAT_KEY = {"b": "B", "v": "B", "w": "B", "c": "K", "k": "K", "q": "K", "x": "KS", "f": "P", "p": "P", "s": "S",
            "t": "T", "z": "Z", "d": "D", "g": "G", "j": "G", "l": "L", "m": "M", "n": "N", "r": "R"}


def phonetic_key(token: str) -> str:
    """Consonant-skeleton key shared by Hebrew script and its Latin transliteration."""
    token = _strip_heb(token.lower())
    out: list[str] = []
    if re.fullmatch(r"[א-ת]+", token):
        for i, ch in enumerate(token):
            if ch == "ו" and i == 0:
                out.append("B")
            elif ch == "ה" and i == 0:
                out.append("H")
            elif ch == "י" and i == 0:
                out.append("Y")
            else:
                out.append(_HEB_KEY.get(ch, ""))
    else:
        i = 0
        while i < len(token):
            two = token[i:i + 2]
            sub = next((v for d, v in _LAT_DIGRAPHS if d == two), None)
            if sub:
                out.append(sub)
                i += 2
                continue
            ch = token[i]
            if ch == "h":
                out.append("H" if i == 0 else "")
            elif ch == "y":
                out.append("Y" if i == 0 else "")
            else:
                out.append(_LAT_KEY.get(ch, ""))
            i += 1
    key = "".join(out)
    return re.sub(r"(.)\1+", r"\1", key)


_PHONETIC_TO_TERM: dict[str, str] = {}
_ambiguous_keys: set[str] = set()
for _heb, _eng in HEBREW_TERMS.items():
    if _eng:
        _k = phonetic_key(_heb)
        if len(_k) >= 2:
            if _k in _PHONETIC_TO_TERM and _PHONETIC_TO_TERM[_k] != _eng:
                _ambiguous_keys.add(_k)
            _PHONETIC_TO_TERM.setdefault(_k, _eng)
for _k in _ambiguous_keys:
    _PHONETIC_TO_TERM.pop(_k, None)

# --------------------------------------------------------------------------- part numbers


def pn_key(pn: str) -> str:
    """Normalized part number: uppercase, separators removed, leading zeros stripped per digit group."""
    s = unicodedata.normalize("NFKC", pn).upper().strip()
    s = re.sub(r"[\s._/\\-]+", "-", s)
    parts = re.findall(r"[A-Z]+|\d+", s)
    return "".join(p.lstrip("0") or "0" if p.isdigit() else p for p in parts)


def pn_core(pn: str) -> str:
    """Digits-only core of a part number (leading zeros stripped per group)."""
    groups = re.findall(r"\d+", pn)
    return "".join(g.lstrip("0") or "0" for g in groups)


def extract_part_numbers(text: str) -> list[str]:
    """Return part-number-like codes found in a name (raw spelling, in order)."""
    found: list[str] = []
    for m in _PN.finditer(text):
        cand = m.group(1).strip(" ._-")
        digits = re.sub(r"\D", "", cand)
        if len(digits) < 4:
            continue
        if not re.match(r"[A-Za-z]", cand) and _DATE.match(digits):
            continue  # looks like a date, not a part number
        found.append(cand)
    return found


# --------------------------------------------------------------------------- descriptions


def _stem(w: str) -> str:
    if w in ENGLISH_VOCAB or w in SYNONYMS:
        return SYNONYMS.get(w, w)
    if len(w) > 5 and w.endswith("ing"):
        base = w[:-3]
        return SYNONYMS.get(base, base)
    if len(w) > 4 and w.endswith("es") and w[:-2] in ENGLISH_VOCAB:
        return w[:-2]
    if len(w) > 3 and w.endswith("s") and not w.endswith("ss"):
        return w[:-1]
    return w


def _norm_number(tok: str) -> str:
    def one(n: str) -> str:
        n = n.replace(",", ".")
        if "." in n:
            a, b = n.split(".", 1)
            b = b.rstrip("0")
            a = a.lstrip("0") or "0"
            return f"{a}.{b}" if b else a
        return n.lstrip("0") or "0"
    if tok.startswith("m"):
        return "m" + one(tok[1:].split("x")[0]) + ("x" + one(tok.split("x")[1]) if "x" in tok else "")
    return "x".join(one(p) for p in tok.split("x"))


def _canon_hebrew(tok: str) -> str | None:
    """Translate a Hebrew token; None if it is noise."""
    t = _strip_heb(tok)
    if t in NOISE_WORDS:
        return None
    if t in HEBREW_TERMS:
        return HEBREW_TERMS[t] or None
    for k in (1, 2):  # strip up to two prefix letters (ו, ה, ב, ל, מ, ש, כ)
        if len(t) - k >= 2 and all(c in _HEB_PREFIXES for c in t[:k]):
            rest = t[k:]
            if rest in HEBREW_TERMS:
                return HEBREW_TERMS[rest] or None
            if rest in NOISE_WORDS:
                return None
    return t  # unknown Hebrew word: keep as is


def _canon_latin(tok: str) -> str | None:
    if tok in NOISE_WORDS:
        return None
    if tok in ABBREVIATIONS:
        return ABBREVIATIONS[tok]
    w = _stem(tok)
    if w in NOISE_WORDS:
        return None
    if w in ENGLISH_VOCAB:
        return w
    if len(tok) >= 4:  # transliterated Hebrew, e.g. "tushevet" -> bracket
        k = phonetic_key(tok)
        if len(k) >= 2 and k in _PHONETIC_TO_TERM:
            return _PHONETIC_TO_TERM[k]
    return w


@dataclass
class NameParts:
    raw: str
    pns: list[str] = field(default_factory=list)       # raw PN spellings
    pn_keys: list[str] = field(default_factory=list)
    words: list[str] = field(default_factory=list)     # canonical words (order kept)
    numbers: list[str] = field(default_factory=list)   # normalized numbers / dimensions
    materials: list[str] = field(default_factory=list) # material mentions (aluminum 6061, ...)

    @property
    def canon(self) -> str:
        return " ".join(sorted(self.words))

    @property
    def display(self) -> str:
        return " ".join(self.pn_keys + sorted(self.words) + sorted(self.numbers))


def parse_name(text: str, known_pns: list[str] | None = None) -> NameParts:
    """Split a free-text name into part numbers, canonical words and numbers."""
    raw = text
    s = unicodedata.normalize("NFKC", text)
    s = _strip_heb(s)
    # camelCase / letter-digit boundaries in Latin words: "MountingBracket" -> "Mounting Bracket"
    s = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", s)
    s, materials = _material_codes(s)  # before PN extraction: AL6061 is a material, not a part number
    pns = extract_part_numbers(s)
    if known_pns:
        pns += [k for k in known_pns if k not in pns]
    for pn in pns:  # remove PN text so its digits do not become description numbers
        s = s.replace(pn, " ")
    low = s.lower()
    low = re.sub(r"(?<=[a-z])['`\u2019](?=[a-z])", "", low)  # taba'at -> tabaat (transliterated ע/א)
    for pat in _NOISE_PATTERNS:
        low = pat.sub(" ", low)

    for phrase, eng in HEBREW_PHRASES.items():
        low = low.replace(phrase, f" {eng} ")
    words: list[str] = []
    numbers: list[str] = []
    for tok in _TOKEN.findall(low):
        if tok[0].isdigit() or (tok[0] == "m" and len(tok) > 1 and tok[1].isdigit()):
            if _DATE.match(tok):
                continue  # dates in file names are not dimensions
            numbers.append(_norm_number(tok))
        elif _strip_heb(tok) in MATERIAL_WORDS or tok in MATERIAL_WORDS:
            materials.append(MATERIAL_WORDS.get(tok) or MATERIAL_WORDS[_strip_heb(tok)])
        elif "א" <= tok[0] <= "ת":
            c = _canon_hebrew(tok)
            if c:
                words.extend(c.split())
        else:
            c = _canon_latin(tok)
            if c in ("aluminum", "stainless", "steel"):
                materials.append(c)
            elif c and len(c) > 1:
                words.extend(c.split())
    for i, mat in enumerate(materials):  # "נירוסטה 304" -> stainless 304
        if " " not in mat:
            grade = next((n for n in numbers if n in GRADES.get(mat, ())), None)
            if grade:
                numbers.remove(grade)
                materials[i] = f"{mat} {grade}"
    return NameParts(raw=raw, pns=pns, pn_keys=[pn_key(p) for p in pns], words=words, numbers=numbers,
                     materials=sorted(set(materials)))


def is_generic_product_name(name: str) -> bool:
    return bool(GENERIC_PRODUCT_NAME.match(name.strip()))


# --------------------------------------------------------------------------- similarity


@dataclass
class NameMatch:
    score: float
    pn_relation: str          # same | core | typo | diff | none
    desc_sim: float
    number_relation: str      # match | conflict | partial | none
    detail: str


def _pn_relation(a: NameParts, b: NameParts) -> str:
    if not a.pn_keys or not b.pn_keys:
        return "none"
    if set(a.pn_keys) & set(b.pn_keys):
        return "same"
    cores_a = {pn_core(p) for p in a.pns if len(pn_core(p)) >= 4}
    cores_b = {pn_core(p) for p in b.pns if len(pn_core(p)) >= 4}
    if cores_a & cores_b:
        return "core"
    for ka in a.pn_keys:
        for kb in b.pn_keys:
            if min(len(ka), len(kb)) >= 5 and OSA.distance(ka, kb) <= 1:
                return "typo"
    return "diff"


def _number_relation(a: NameParts, b: NameParts) -> str:
    na, nb = set(a.numbers), set(b.numbers)
    if not na and not nb:
        return "none"
    if not na or not nb:
        return "partial"
    return "match" if na == nb else "conflict"


def desc_similarity(a: NameParts, b: NameParts) -> float:
    if not a.words or not b.words:
        return 0.0
    ca, cb = a.canon, b.canon
    ts = fuzz.token_set_ratio(ca, cb) / 100.0
    tso = fuzz.token_sort_ratio(ca, cb) / 100.0
    sim = 0.25 * ts + 0.75 * tso  # a name that is a subset of another is weaker evidence
    if min(len(a.words), len(b.words)) == 1 and len(set(a.words) ^ set(b.words)) > 0:
        sim *= 0.85  # a single generic word ("bracket") is weak evidence
    return sim


class NameIndex:
    """Corpus statistics used to discount generic descriptions.

    A 'unit' is one distinct part number (files without a PN count individually), so
    several copies of the same PN do not make its description look generic.
    """

    def __init__(self, items: dict[str, list[NameParts]], unit_of: dict[str, str] | None = None, k0: int = 3,
                 partial_factor: float = 0.9):
        self.k0 = k0
        self.partial_factor = partial_factor
        self._joint: dict[frozenset, int] = {}
        self.postings: dict[str, set[str]] = defaultdict(set)
        unit_of = unit_of or {}
        for iid, sources in items.items():
            unit = unit_of.get(iid) or f"id:{iid}"
            for np_ in sources:
                for t in set(np_.words) | set(np_.numbers):
                    self.postings[t].add(unit)

    def joint_count(self, tokens) -> int:
        key = frozenset(tokens)
        hit = self._joint.get(key)
        if hit is not None:
            return hit
        sets = sorted((self.postings.get(t, set()) for t in key), key=len)
        n = len(sets[0].intersection(*sets[1:])) if sets else 0
        self._joint[key] = n
        return n

    def specificity(self, a: NameParts, b: NameParts) -> tuple[float, int]:
        """1.0 if at most k0 distinct parts carry the shared description, lower when it is generic."""
        ta, tb = set(a.words) | set(a.numbers), set(b.words) | set(b.numbers)
        shared = ta & tb
        if not shared:  # typos: use the smaller name's tokens that have a close partner
            small, big = (ta, tb) if len(ta) <= len(tb) else (tb, ta)
            shared = {t for t in small if any(fuzz.ratio(t, u) >= 80 for u in big)}
        m = self.joint_count(shared) if shared else 0
        if m <= self.k0:
            return 1.0, m
        return math.sqrt(self.k0 / m), m


def compare_names(a: NameParts, b: NameParts, index: "NameIndex | None" = None) -> NameMatch:
    pn_rel = _pn_relation(a, b)
    num_rel = _number_relation(a, b)
    ds = desc_similarity(a, b)
    partial = index.partial_factor if index is not None else 0.9
    desc_score = ds * {"conflict": 0.5, "partial": partial}.get(num_rel, 1.0)
    mat_rel = "none"
    if a.materials and b.materials:
        mat_rel = "match" if set(a.materials) == set(b.materials) else "conflict"
    elif a.materials or b.materials:
        mat_rel = "partial"
    desc_score *= {"conflict": 0.5, "partial": partial}.get(mat_rel, 1.0)
    spec_note = "" if mat_rel == "none" else f"; materials={mat_rel}"
    if index is not None and pn_rel not in ("same", "core") and desc_score >= 0.6:
        spec, m = index.specificity(a, b)
        if spec < 1.0:
            desc_score *= spec
            spec_note += f"; generic description shared by {m} part numbers (x{spec:.2f})"
    if pn_rel == "same":
        score, why = 1.0, "same part number"
    elif pn_rel == "core":
        score, why = 0.95, "same part number digits (prefix/format differs)"
    elif pn_rel == "typo":
        # one-character PN differences are just as often sequential numbers of
        # different parts, so this is only a small bonus on the description match
        score, why = min(1.0, desc_score + 0.05), "part numbers differ by one character"
    else:
        score, why = desc_score, "description similarity"
    detail = f"{why}; desc_sim={ds:.2f}; numbers={num_rel}{spec_note}"
    return NameMatch(score=round(score, 4), pn_relation=pn_rel, desc_sim=round(ds, 4), number_relation=num_rel, detail=detail)


def best_match(sources_a: list[NameParts], sources_b: list[NameParts], index: "NameIndex | None" = None) -> NameMatch | None:
    """Best comparison over all name sources of two items (file name, STEP product, ERP row)."""
    best: NameMatch | None = None
    for a in sources_a:
        for b in sources_b:
            m = compare_names(a, b, index)
            if best is None or m.score > best.score:
                best = m
    return best


def blocking_pairs(items: dict[str, list[NameParts]], max_block: int = 60) -> set[tuple[str, str]]:
    """Candidate pairs sharing a PN core, a PN key, a rare word or a word pair.

    ``items`` maps an id to its name sources. Blocks bigger than ``max_block`` are
    skipped for single words (too generic) and replaced by word-pair blocks.
    """
    blocks: dict[str, set[str]] = defaultdict(set)
    for iid, sources in items.items():
        for np_ in sources:
            for p in np_.pns:
                core = pn_core(p)
                if len(core) >= 4:
                    blocks["c:" + core].add(iid)
                    if len(core) >= 5:  # typo-tolerant: one substituted digit or two swapped digits
                        for k in range(len(core)):
                            blocks["cd:" + core[:k] + "_" + core[k + 1:]].add(iid)
                        for k in range(len(core) - 1):
                            blocks["cs:" + core[:k] + "__" + core[k + 2:]].add(iid)
            for k in np_.pn_keys:
                blocks["k:" + k].add(iid)
            uniq = sorted(set(np_.words))
            for w in uniq:
                blocks["w:" + w].add(iid)
            for w1, w2 in combinations(uniq, 2):
                blocks["ww:" + w1 + "|" + w2].add(iid)
    pairs: set[tuple[str, str]] = set()
    for key, ids in blocks.items():
        if len(ids) < 2:
            continue
        if len(ids) > max_block and (key.startswith("w:") or key.startswith("ww:")):
            continue
        if len(ids) > 4 * max_block:
            continue
        for a, b in combinations(sorted(ids), 2):
            pairs.add((a, b))
    return pairs
