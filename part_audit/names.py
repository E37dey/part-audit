"""L2 - part-number and description normalization and fuzzy name matching.

The pipeline for a free-text name (file name, STEP product name, ERP description):

1. Extract part-number-like codes (``PA-0123``, ``100-2345-01``...) and normalize
   them: uppercase, no separators, no leading zeros per digit group.
2. Remove noise (old/final/copy/rev B/v2/(1)/ישן/סופי/עותק...).
3. Tokenize into words and numbers/dimensions; translate Hebrew terms and expand
   English abbreviations to one canonical English vocabulary; Hebrew written in
   Latin letters ("tushevet") is matched through a consonant-skeleton key.
4. Compare two names with rapidfuzz (token_set / token_sort) on the canonical
   words, with part-number and number/dimension agreement as extra evidence.

Candidate pairs are generated by blocking (shared PN core / shared rare token /
shared token pair) so the comparison is not all-pairs.
"""
